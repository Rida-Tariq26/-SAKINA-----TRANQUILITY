-- 1. Users Table (Google authenticated users & guest sessions)
CREATE TABLE IF NOT EXISTS users (
    user_id    TEXT PRIMARY KEY,
    email      TEXT NOT NULL,
    name       TEXT,
    picture    TEXT,
    created_at TEXT NOT NULL,
    deleted_at TEXT
);

-- 2. Mood Logs Table (Per-user longitudinal mood logs)
CREATE TABLE IF NOT EXISTS mood_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    TEXT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    timestamp  TEXT NOT NULL,
    state      TEXT NOT NULL,
    intensity  INTEGER NOT NULL,
    note       TEXT DEFAULT ''
);

-- 3. Journal Entries Table (Per-user private journal reflections)
CREATE TABLE IF NOT EXISTS journal_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    TEXT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    title      TEXT NOT NULL,
    content    TEXT NOT NULL,
    mood       TEXT DEFAULT '',
    prompt     TEXT DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

-- 4. Feedback & Reviews Table (Public reviews & feedback submissions)
CREATE TABLE IF NOT EXISTS feedback (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_type TEXT NOT NULL DEFAULT 'review',
    rating        INTEGER,
    message       TEXT NOT NULL,
    name          TEXT DEFAULT 'Anonymous',
    email         TEXT,
    ip_hash       TEXT,
    user_agent    TEXT,
    is_approved   INTEGER NOT NULL DEFAULT 1,
    created_at    TEXT NOT NULL
);

-- 5. Performance Indexes
CREATE INDEX IF NOT EXISTS idx_mood_user ON mood_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_mood_user_timestamp ON mood_logs(user_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_journal_user ON journal_entries(user_id);
CREATE INDEX IF NOT EXISTS idx_journal_user_created ON journal_entries(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedback_created ON feedback(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedback_type ON feedback(feedback_type);
CREATE INDEX IF NOT EXISTS idx_feedback_ip_created ON feedback(ip_hash, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedback_approved ON feedback(is_approved, created_at DESC);

-- 6. Row Level Security (RLS) Configuration
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE mood_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE journal_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE feedback ENABLE ROW LEVEL SECURITY;

-- Idempotent RLS Policies: Allow backend service_role and authenticated/anon backend access
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'users' AND policyname = 'Sakina backend access for users'
    ) THEN
        CREATE POLICY "Sakina backend access for users" ON users FOR ALL USING (true) WITH CHECK (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'mood_logs' AND policyname = 'Sakina backend access for mood_logs'
    ) THEN
        CREATE POLICY "Sakina backend access for mood_logs" ON mood_logs FOR ALL USING (true) WITH CHECK (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'journal_entries' AND policyname = 'Sakina backend access for journal_entries'
    ) THEN
        CREATE POLICY "Sakina backend access for journal_entries" ON journal_entries FOR ALL USING (true) WITH CHECK (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'feedback' AND policyname = 'Sakina backend access for feedback'
    ) THEN
        CREATE POLICY "Sakina backend access for feedback" ON feedback FOR ALL USING (true) WITH CHECK (true);
    END IF;
END $$;
